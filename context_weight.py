"""Вес собранного контекста запроса — строка для финальной тик-заметки.

Делает бюджет контекста видимым самому агенту: размер считается по
готовому массиву messages (включая финальное user-сообщение с этой
заметкой — она честно включает и саму себя), 1 КБ = 1024 Б, точность —
одна десятая КБ. Чистая функция, зависимостей нет.
"""

import json


def weight_note(messages: list[dict], iterations: int) -> str:
    """«(контекст запроса: ~12.4 КБ, 18 итераций)» для финального тика.

    `messages` — весь запрос целиком (system + история + заметки +
    финальное user-сообщение), `iterations` — номер наступающей итерации
    текущей сессии.
    """
    size_kb = len(json.dumps(messages, ensure_ascii=False).encode("utf-8")) / 1024
    return f"(контекст запроса: ~{size_kb:.1f} КБ, {iterations} итераций)"
